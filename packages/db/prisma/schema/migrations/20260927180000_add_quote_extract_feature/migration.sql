-- Feature 5, the switch half: one enum value, so reading a sub's quote can be
-- turned off independently of everything else AI does here.
--
-- FULLY ADDITIVE, and it is one statement. No table, no column, no index. The
-- running build does not read this value, so there is no expand/contract window
-- (#378) to think about.
--
-- WHY ITS OWN MEMBER RATHER THAN REUSING `COMPLIANCE_EXTRACT`, which would have
-- needed no migration at all: a contractor happy for us to read their own lien
-- waivers may not be happy for us to read a competitor's pricing. Those are two
-- different questions about two different kinds of document, and the entire
-- reason `disabledFeatures` is a list rather than one flag is so they can be
-- answered differently. A shared member would have made the cheaper migration
-- and the worse product.
--
-- GENERATED BY A SCHEMA-TO-SCHEMA DIFF — `--from-schema-datamodel` against HEAD,
-- `--to-schema-datamodel` against the working tree. NO DATABASE WAS CONNECTED
-- TO, which is the rule rather than a preference: `--shadow-database-url` DROPS
-- AND RECREATES whatever it is pointed at, and on 2026-09-18 it was pointed at
-- ep-icy-hat and took every company, job and test record with it.
--
-- ONE POSTGRES DETAIL, FLAGGED BECAUSE IT IS THE THING THAT WOULD BITE: an
-- `ALTER TYPE … ADD VALUE` may run inside a transaction on PG 12+, but the new
-- value CANNOT BE USED in that same transaction. Prisma wraps each migration in
-- one, so a migration that added the value and then wrote a row using it would
-- fail — which is exactly why this file adds the value and nothing else. Any
-- backfill using `QUOTE_EXTRACT` belongs in a later migration, and nothing here
-- needs one: the value's whole purpose is to be absent from
-- `disabledFeatures` until a company chooses otherwise, and absent is the
-- default.
-- AlterEnum
ALTER TYPE "AiFeature" ADD VALUE 'QUOTE_EXTRACT';
